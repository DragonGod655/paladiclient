package paladi.client.mixin;

import paladi.client.systems.modules.Modules;
import paladi.client.systems.modules.player.NameProtect;
import paladi.client.systems.modules.krypton.FakeStats;
import net.minecraft.text.TextVisitFactory;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.ModifyArg;

@Mixin(TextVisitFactory.class)
public abstract class TextVisitFactoryMixin {
    @ModifyArg(at = @At(value = "INVOKE",
            target = "Lnet/minecraft/text/TextVisitFactory;visitFormatted(Ljava/lang/String;ILnet/minecraft/text/Style;Lnet/minecraft/text/Style;Lnet/minecraft/text/CharacterVisitor;)Z",
            ordinal = 0),
            method = {
                    "visitFormatted(Ljava/lang/String;ILnet/minecraft/text/Style;Lnet/minecraft/text/CharacterVisitor;)Z"},
            index = 0)
    private static String adjustText(String text) {
        if (Modules.get() != null) {
            text = Modules.get().get(NameProtect.class).replaceName(text);
            text = Modules.get().get(FakeStats.class).replaceText(text);
            return text;
        }
        return text;
    }
}
