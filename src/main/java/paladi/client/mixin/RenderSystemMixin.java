package paladi.client.mixin;

import com.mojang.blaze3d.systems.RenderSystem;
import paladi.client.renderer.MeshUniforms;
import paladi.client.systems.modules.Modules;
import paladi.client.systems.modules.misc.InventoryTweaks;
import paladi.client.utils.render.postprocess.ChamsShader;
import paladi.client.utils.render.postprocess.OutlineUniforms;
import paladi.client.utils.render.postprocess.PostProcessShader;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

import static paladi.client.PaladiClient.mc;

@Mixin(RenderSystem.class)
public abstract class RenderSystemMixin {
    @Inject(method = "flipFrame", at = @At("TAIL"))
    private static void Paladi$flipFrame(CallbackInfo info) {
        MeshUniforms.flipFrame();
        PostProcessShader.flipFrame();
        ChamsShader.flipFrame();
        OutlineUniforms.flipFrame();

        if (Modules.get() == null || mc.player == null) return;
        if (Modules.get().get(InventoryTweaks.class).frameInput()) ((MinecraftClientAccessor) mc).Paladi$handleInputEvents();
    }
}
