package paladi.client.gui.tabs.builtin;

import paladi.client.gui.GuiTheme;
import paladi.client.gui.GuiThemes;
import paladi.client.gui.tabs.Tab;
import paladi.client.gui.tabs.TabScreen;
import net.minecraft.client.gui.screen.Screen;

public class ModulesTab extends Tab {
    public ModulesTab() {
        super("Modules");
    }

    @Override
    public TabScreen createScreen(GuiTheme theme) {
        return theme.modulesScreen();
    }

    @Override
    public boolean isScreen(Screen screen) {
        return GuiThemes.get().isModulesScreen(screen);
    }
}
